/* Pokemon Torre V80, real impact synchronization for the TWO opt-in ranged moves.
 * Runs AFTER V47 collision-recovery wrapper. Never edits hitTarget(), RNG,
 * damage amounts, energy/cooldown or approved electric/contact moves.
 * The existing v359 attack update remains the single authoritative hit path.
 */
(function(){
 'use strict';
 const norm=s=>String(s||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'')
   .toLowerCase().replace(/[^a-z0-9]/g,'');
 const names=new Set(['dragonpulse','aurasphere']);
 const log={version:'80.0',scheduled:0,recoverySuppressed:0,last:null};
 const oldMove=BattleEngine.prototype.useMove;
 BattleEngine.prototype.useMove=function(slot){
  const had=new Set(this.v359Attacks||[]);
  const priorRecovery=new Set(this.v47MissingCollisions||[]);
  const prevContact=new Set(this.v47ContactToLand||[]);
  const result=oldMove.apply(this,arguments);
  if(result===false||!battle?.active||battle.paused)return result;
  const fx=(this.v359Attacks||[]).findLast(event=>event&&
    !had.has(event)&&event.battle===battle&&event.owner===current()&&
    names.has(norm(event.move?.name))&&event.hits===0&&
    Number.isFinite(event.at)&&Number(event.duration)>0);
  if(!fx)return result;
  const config=window.PokemonTorreBattlePreviewV80?.synchronization;
  if(!config||config.impactFrame!==5||
     config.impactFraction!==5/8||config.rangedSlowdown!==3.4)return result;
  const visualMs=Math.max(250,fx.duration)*config.rangedSlowdown;
  const contactMs=visualMs*config.impactFraction;
  // This game natively reads fx.at + fx.duration * fx.times[nextHit].
  // Times CAN exceed 1 when the animation runs longer than the mechanical cast.
  // Retain original fx.duration and hitTarget(); there is still just ONE hit.
  fx.times=[contactMs/fx.duration];
  fx.end=Math.max(fx.end||0,fx.at+visualMs+240);
  fx.v80ImpactAt=fx.at+contactMs;
  fx.v80VisualUntil=fx.at+visualMs;
  fx.v80Synced=true;
  // V47's optional missing-collision fallback is designed for older attacks.
  // Without suppression it could deal early damage (~770 ms), bypassing v359.
  // Remove ONLY fallback entries generated by THIS newly accepted cast.
  const before=this.v47MissingCollisions?.length||0;
  if(before){
   this.v47MissingCollisions=this.v47MissingCollisions.filter(event=>
     priorRecovery.has(event)||norm(event.name)!==norm(fx.move.name)||
     event.owner!==fx.owner||event.victim!==fx.target);
  }
  const contactBefore=this.v47ContactToLand?.length||0;
  if(contactBefore){
   this.v47ContactToLand=this.v47ContactToLand.filter(event=>
     prevContact.has(event)||norm(event.name)!==norm(fx.move.name)||
     event.owner!==fx.owner||event.victim!==fx.target);
  }
  log.recoverySuppressed+=before-(this.v47MissingCollisions?.length||0)+
      contactBefore-(this.v47ContactToLand?.length||0);
  log.scheduled++;
  log.last={name:fx.move.name,castAt:fx.at,impactAt:fx.v80ImpactAt,
    visualUntil:fx.v80VisualUntil,hitCount:fx.times.length,
    originalDuration:fx.duration};
  return result;
 };
 window.PokemonTorreHitSyncV80=()=>({...log,last:log.last&&{...log.last}});
})();
